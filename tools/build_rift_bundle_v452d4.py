#!/usr/bin/env python3
"""Build certified elemental Rift deltas from approved black/white masks.

Usage:
 python tools/build_rift_bundle_v452d4.py --base data/masks_128.json --element mountain \
     --wall approved_mountain_wall.png --output data/generated_mountain.json

A supplied mask encodes the FULL resulting layer (not merely a new region).
Black=not occupied; white=occupied. Explicit dimensions and binary pixels are required.
No source topology is inferred, rescaled, or generated by this script.
"""
import argparse
import json
import hashlib
from pathlib import Path


def grayscale_mask(filename: str, size: int) -> str:
    try:
        from PIL import Image
    except ImportError as error:
        raise SystemExit('Pillow required: python -m pip install pillow') from error
    with Image.open(filename) as image:
        if image.size != (size, size):
            raise ValueError(f'{filename}: expected exact {size}x{size} pixels; got {image.size}')
        if image.mode not in ('1', 'L'):
            raise ValueError(f'{filename}: use single-channel 1/L PNG; no RGBA ambiguity')
        image = image.convert('L')
        pixels = list(image.get_flattened_data() if hasattr(image, "get_flattened_data") else image.getdata())
        if any(v not in (0, 255) for v in pixels):
            raise ValueError(f'{filename}: mask pixels must be exactly 0 or 255')
        return ''.join('1' if v == 255 else '0' for v in pixels)


def changes(baseline, proposed):
    return ([i for i, (x, y) in enumerate(zip(baseline, proposed)) if x == '0' and y == '1'],
            [i for i, (x, y) in enumerate(zip(baseline, proposed)) if x == '1' and y == '0'])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--base', required=True)
    parser.add_argument('--element', required=True, choices=['mountain', 'ocean', 'infernal', 'cloud', 'hextech', 'chemtech'])
    parser.add_argument('--wall')
    parser.add_argument('--brush')
    parser.add_argument('--features', help='Optional JSON file with manually certified coordinates and feature IDs')
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    base = json.loads(Path(args.base).read_text(encoding='utf-8'))
    size = base['size']
    if len(base['wall']) != size * size or len(base['brush']) != size * size:
        raise ValueError('The base atlas has inconsistent width/height')
    result = dict(schema='coachlol.rift-bundle.v1', size=size, element=args.element,
                  addWall=[], removeWall=[], addBrush=[], removeBrush=[], features={})
    for key, flag in [('wall', args.wall), ('brush', args.brush)]:
        if flag:
            added, removed = changes(base[key], grayscale_mask(flag, size))
            suffix = 'Wall' if key == 'wall' else 'Brush'
            result['add'+suffix], result['remove'+suffix] = added, removed
    if args.element == 'infernal' and any(result[k] for k in ('addWall', 'removeWall', 'addBrush', 'removeBrush')):
        raise ValueError('Infernal 14.1+: no wall or brush destruction; use cinderSites')
    if args.element == 'mountain' and (result['addBrush'] or result['removeBrush']):
        raise ValueError('Mountain alpha: only wall differences are supported')
    if args.element == 'ocean' and (result['addWall'] or result['removeWall']):
        raise ValueError('Ocean alpha: only brush differences are supported')
    if args.features:
        features = json.loads(Path(args.features).read_text(encoding='utf-8'))
        if not isinstance(features, dict):
            raise ValueError('features JSON must be an object of arrays')
        result['features'] = features
    fingerprint = hashlib.sha256((base['wall'] + '\n' + base['brush']).encode()).hexdigest()
    report = dict(schema='coachlol.rift-validation.v1', element=args.element, atlasSize=size,
                  sourceBaseHash=fingerprint,
                  changes={k:len(result[k]) for k in ('addWall','removeWall','addBrush','removeBrush')},
                  gameplayGeometryCertified=False,
                  note='Human review of coordinate calibration, paths and collisions required before certification.')
    out = Path(args.output);out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    report_path = out.with_name(out.stem+'.validation.json')
    report_path.write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    print(f'{out}: {sum(report["changes"].values())} changed cells; QA report: {report_path}')

if __name__ == '__main__':
    main()
