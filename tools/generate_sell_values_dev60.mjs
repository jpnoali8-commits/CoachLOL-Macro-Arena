/** Gera tabela auditável de revenda do pacote Data Dragon 16.21.1 (Summoner's Rift) */
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const sr=JSON.parse(readFileSync(new URL('data/riot_reference/sr_shop_26_21_dev49.json',root),'utf8'));
const official=JSON.parse(readFileSync(new URL('data/riot_reference/source_16_21_1/riot/16.21.1/pt_BR/item.json',root),'utf8')).data;
const pairs=Object.values(sr.rows).filter(x=>x.status==='engine_playable').map(row=>{
 const raw=official[row.id];
 if(!raw||raw.maps?.['11']!==true||!Number.isInteger(raw.gold?.sell)||raw.gold.sell<0||!row.localId||raw.gold.total!==row.price)throw Error('inconsistent_riot_sale_'+row.id);
 return [row.localId,raw.gold.sell];
}).sort((a,b)=>a[0].localeCompare(b[0]));
if(pairs.length!==sr.counts.normalPlayable||new Set(pairs.map(x=>x[0])).size!==pairs.length)throw Error('sell_coverage_mismatch');
const content='// GENERATED BY tools/generate_sell_values_dev60.mjs — Data Dragon 16.21.1, SR patch 26.21.\n'
 +'// gold.sell values from Riot source, NEVER a generic 70% fallback.\n'
 +'export const ITEM_SELL_VALUES_V453_DEV60 = Object.freeze('+JSON.stringify(Object.fromEntries(pairs),null,1)+');\n'
 +'export function officialSaleValueV453Dev60(id){return Object.hasOwn(ITEM_SELL_VALUES_V453_DEV60,id)?ITEM_SELL_VALUES_V453_DEV60[id]:null;}\n';
writeFileSync(new URL('data/riot_reference/sr_sell_values_26_21_dev60.js',root),content);
console.log('generated',pairs.length,'official sale values');
