#[cfg(test)]
mod tests {
    use super::*;
    use crate::CATALOG;
    #[test]
    fn every_legacy_item_has_a_base_stats_record() {
        assert_eq!(CATALOG.len(), 125);
        assert_eq!(ITEM_STATS.len(), 125);
        for spec in CATALOG {
            assert!(item_stats(spec.id).is_some(), "no stats row: {}", spec.id);
        }
        assert_eq!(item_stats("dorans_ring").unwrap().values,
            &[("ap", 18.0), ("hp", 90.0)]);
    }
}
