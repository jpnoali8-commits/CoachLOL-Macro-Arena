//! M45 B02B-I11: session-gated PvP public JSON/SSE projection.
//! Transport-independent boundary, NOT an actual HTTP server.
//! The future server MUST securely generate two independent 256-bit bearer
//! tokens with an OS CSPRNG, use TLS, and keep them server-side. NEVER accept
//! a client-provided team field, state snapshot, raw event or session registry.
//! No crypto RNG, network authentication or cookie parser is implemented here.
use crate::pvp_projection::{PrivatePvPEvent, SeatPublicProjection};
use crate::skill_authority::ServerSkillWorld;
use crate::Team;

pub const SESSION_TOKEN_BYTES: usize = 32;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SessionAuthError {
    InvalidTokenMaterial,
    InvalidRoomId,
    Unauthorized,
}

struct SessionBinding {
    secret: [u8; SESSION_TOKEN_BYTES],
    active: bool,
}

/// Does NOT implement Debug, Clone, Serialize or token accessors. Keep this
/// object private to the authoritative server's room/session registry.
pub struct SessionGate {
    room_id: String,
    blue: SessionBinding,
    red: SessionBinding,
}

fn invalid_token_material(token: &[u8; SESSION_TOKEN_BYTES]) -> bool {
    // All-zero values are obviously unsafe; any other value must STILL be
    // generated by a real CSPRNG. This check cannot prove token entropy.
    token.iter().all(|byte| *byte == 0)
}

fn token_equals(stored: &[u8; SESSION_TOKEN_BYTES], supplied: &[u8]) -> bool {
    let mut difference = (supplied.len() != SESSION_TOKEN_BYTES) as u8;
    for (index, stored_byte) in stored.iter().enumerate() {
        difference |= *stored_byte ^ supplied.get(index).copied().unwrap_or(0);
    }
    // Fixed loop does not claim compiler-guaranteed constant-time behavior.
    difference == 0
}

impl SessionGate {
    /// Takes two tokens created by an external trusted OS-random source.
    /// The test fixtures use repeated byte arrays ONLY in unit tests.
    pub fn from_server_generated_tokens(
        room_id: &str,
        blue: [u8; SESSION_TOKEN_BYTES],
        red: [u8; SESSION_TOKEN_BYTES],
    ) -> Result<Self, SessionAuthError> {
        if room_id.is_empty() || room_id.len() > crate::skill_admission::MAX_ID_BYTES {
            return Err(SessionAuthError::InvalidRoomId);
        }
        if invalid_token_material(&blue) || invalid_token_material(&red) || blue == red {
            return Err(SessionAuthError::InvalidTokenMaterial);
        }
        Ok(Self {
            room_id: room_id.to_owned(),
            blue: SessionBinding { secret: blue, active: true },
            red: SessionBinding { secret: red, active: true },
        })
    }

    fn authorize_world(
        &self,
        bearer: &[u8],
        world: &ServerSkillWorld,
    ) -> Result<Team, SessionAuthError> {
        let seat = self.authenticate(bearer)?;
        if world.source_room_id() != Some(self.room_id.as_str()) {
            return Err(SessionAuthError::Unauthorized);
        }
        Ok(seat)
    }

    fn authenticate(&self, supplied: &[u8]) -> Result<Team, SessionAuthError> {
        // Compare both stored tokens; do not accept arbitrary user-supplied
        // team identifiers and never include token or seat in an error string.
        let blue_matches = token_equals(&self.blue.secret, supplied);
        let red_matches = token_equals(&self.red.secret, supplied);
        if blue_matches && self.blue.active {
            Ok(Team::Blue)
        } else if red_matches && self.red.active {
            Ok(Team::Red)
        } else {
            Err(SessionAuthError::Unauthorized)
        }
    }

    /// Trusted server operation; revocation affects each next publication.
    pub fn revoke(&mut self, seat: Team) {
        match seat {
            Team::Blue => self.blue.active = false,
            Team::Red => self.red.active = false,
        }
    }

    /// Trusted server operation for reconnect/session replacement. A new token
    /// must be generated independently using an OS CSPRNG.
    pub fn rotate(
        &mut self,
        seat: Team,
        replacement: [u8; SESSION_TOKEN_BYTES],
    ) -> Result<(), SessionAuthError> {
        if invalid_token_material(&replacement) {
            return Err(SessionAuthError::InvalidTokenMaterial);
        }
        match seat {
            Team::Blue => {
                if replacement == self.blue.secret || replacement == self.red.secret {
                    return Err(SessionAuthError::InvalidTokenMaterial);
                }
                self.blue.secret = replacement;
                self.blue.active = true;
            }
            Team::Red => {
                if replacement == self.red.secret || replacement == self.blue.secret {
                    return Err(SessionAuthError::InvalidTokenMaterial);
                }
                self.red.secret = replacement;
                self.red.active = true;
            }
        }
        Ok(())
    }

    /// This API has NO seat argument. Seat derives solely from the authenticated
    /// credential; a wrong or revoked bearer receives no bytes of match state.
    pub fn public_json(
        &self,
        bearer: &[u8],
        world: &ServerSkillWorld,
        events: &[PrivatePvPEvent],
    ) -> Result<String, SessionAuthError> {
        let seat = self.authorize_world(bearer, world)?;
        Ok(SeatPublicProjection::from_private(world, seat, events).to_public_json())
    }

    /// Only this session-gated entry should feed the future HTTP/SSE endpoint.
    /// A real server must still enforce request size, origin/cookie policy,
    /// TLS and disconnection/reconnect lifecycle.
    pub fn sse_frame(
        &self,
        bearer: &[u8],
        world: &ServerSkillWorld,
        events: &[PrivatePvPEvent],
    ) -> Result<String, SessionAuthError> {
        let seat = self.authorize_world(bearer, world)?;
        Ok(SeatPublicProjection::from_private(world, seat, events).to_sse_frame())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::skill_authority::{BoardPoint, ServerSkillSnapshot, ServerUnitSnapshot};

    fn gate() -> SessionGate {
        SessionGate::from_server_generated_tokens("room-blue-red", [1u8; 32], [2u8; 32]).unwrap()
    }
    fn unit(id: &str, team: Team) -> ServerUnitSnapshot {
        ServerUnitSnapshot {
            id: id.into(),
            champion: "TestChampion".into(),
            team,
            pos: BoardPoint { x: 0, y: 0 },
            alive: true,
            visible_to_blue: false,
            visible_to_red: false,
            mana: 9123,
            skill: [ServerSkillSnapshot {
                rank: 2, ready_at_tick: 99999, mana_cost: 500, max_range: 600,
            }; 4],
        }
    }
    fn world() -> ServerSkillWorld {
        ServerSkillWorld::from_authoritative_units_in_room("room-blue-red", 50, vec![
            unit("BLUE_PRIVATE", Team::Blue),
            unit("RED_PRIVATE", Team::Red),
        ]).unwrap()
    }

    #[test]
    fn missing_malformed_or_wrong_token_cannot_obtain_sse_or_json() {
        let gate = gate();
        let world = world();
        for bad in [vec![], vec![1u8; 31], vec![1u8; 33], vec![9u8; 32]] {
            assert_eq!(gate.public_json(&bad, &world, &[]),
                Err(SessionAuthError::Unauthorized));
            assert_eq!(gate.sse_frame(&bad, &world, &[]),
                Err(SessionAuthError::Unauthorized));
        }
    }

    #[test]
    fn blue_session_only_receives_own_hidden_units() {
        let world = world();
        let json = gate().public_json(&[1u8; 32], &world, &[]).unwrap();
        assert!(json.contains("BLUE_PRIVATE"));
        assert!(!json.contains("RED_PRIVATE"));
        assert!(json.contains("\"seat\":\"blue\""));
        assert!(json.contains("\"ownMana\":9123"));
    }

    #[test]
    fn red_session_cannot_spoof_blue_view() {
        let world = world();
        let frame = gate().sse_frame(&[2u8; 32], &world, &[]).unwrap();
        assert!(frame.contains("RED_PRIVATE"));
        assert!(!frame.contains("BLUE_PRIVATE"));
        assert!(frame.contains("\"seat\":\"red\""));
        assert_eq!(frame.matches("\ndata: ").count(), 1);
    }

    #[test]
    fn revoke_prevents_future_publishing_without_affecting_other_seat() {
        let mut gate = gate();
        let world = world();
        assert!(gate.public_json(&[1u8; 32], &world, &[]).is_ok());
        gate.revoke(Team::Blue);
        assert_eq!(gate.public_json(&[1u8; 32], &world, &[]),
            Err(SessionAuthError::Unauthorized));
        assert_eq!(gate.sse_frame(&[1u8; 32], &world, &[]),
            Err(SessionAuthError::Unauthorized));
        assert!(gate.sse_frame(&[2u8; 32], &world, &[]).is_ok());
    }

    #[test]
    fn rotating_credential_revokes_old_token_and_activates_new_one() {
        let mut gate = gate();
        let world = world();
        gate.rotate(Team::Blue, [3u8; 32]).unwrap();
        assert_eq!(gate.public_json(&[1u8; 32], &world, &[]),
            Err(SessionAuthError::Unauthorized));
        assert!(gate.public_json(&[3u8; 32], &world, &[]).is_ok());
        assert!(gate.public_json(&[2u8; 32], &world, &[]).is_ok());
    }

    #[test]
    fn duplicate_or_zero_tokens_fail_closed_on_registration_and_rotation() {
        assert!(matches!(
            SessionGate::from_server_generated_tokens("room-blue-red", [1u8; 32], [1u8; 32]),
            Err(SessionAuthError::InvalidTokenMaterial)
        ));
        assert!(matches!(
            SessionGate::from_server_generated_tokens("room-blue-red", [0u8; 32], [2u8; 32]),
            Err(SessionAuthError::InvalidTokenMaterial)
        ));
        let mut gate = gate();
        assert_eq!(gate.rotate(Team::Blue, [2u8; 32]),
            Err(SessionAuthError::InvalidTokenMaterial));
        assert_eq!(gate.rotate(Team::Red, [0u8; 32]),
            Err(SessionAuthError::InvalidTokenMaterial));
        assert!(gate.public_json(&[1u8; 32], &world(), &[]).is_ok());
        assert!(gate.public_json(&[2u8; 32], &world(), &[]).is_ok());
    }

    #[test]
    fn revoked_seat_can_reconnect_only_with_a_new_secret() {
        let mut gate = gate();
        gate.revoke(Team::Red);
        gate.rotate(Team::Red, [4u8; 32]).unwrap();
        assert_eq!(gate.sse_frame(&[2u8; 32], &world(), &[]),
            Err(SessionAuthError::Unauthorized));
        assert!(gate.sse_frame(&[4u8; 32], &world(), &[]).is_ok());
    }

    #[test]
    fn private_order_and_objective_roll_remain_hidden_after_auth() {
        let world = world();
        let events = vec![
            PrivatePvPEvent::submitted_order(
                Team::Red, "RED_PRIVATE".into(), Some("SECRET_TARGET".into()),
                "PRIVATE_REQUEST_ID".into(), 991231),
            PrivatePvPEvent::hidden_objective("SECRET_BARON".into(), 78912),
        ];
        for bearer in [[1u8; 32], [2u8; 32]] {
            let body = gate().sse_frame(&bearer, &world, &events).unwrap();
            for secret in [
                "SECRET_TARGET", "PRIVATE_REQUEST_ID", "SECRET_BARON", "991231", "78912",
            ] {
                assert!(!body.contains(secret));
            }
        }
    }

    #[test]
    fn event_cannot_leak_hidden_cross_seat_target() {
        let world = world();
        let events = vec![PrivatePvPEvent::combat_impact(
            "BLUE_PRIVATE".into(), "RED_PRIVATE".into(), 89999, 76123,
        )];
        for bearer in [[1u8; 32], [2u8; 32]] {
            let frame = gate().sse_frame(&bearer, &world, &events).unwrap();
            assert!(!frame.contains("\"kind\":\"visible_impact\""));
            assert!(!frame.contains("89999"));
            assert!(!frame.contains("76123"));
        }
    }

    #[test]
    fn sse_frame_never_serializes_session_tokens_or_internal_skill_state() {
        let world = world();
        let frame = gate().sse_frame(&[1u8; 32], &world, &[]).unwrap();
        assert!(frame.starts_with("event: public_state\ndata: {"));
        assert!(!frame.contains("ready_at_tick"));
        assert!(!frame.contains("mana_cost"));
        assert!(!frame.contains("visible_to_blue"));
        assert!(!frame.contains("SECRET_TOKEN"));
        assert_eq!(frame.matches("event: ").count(), 1);
    }

    #[test]
    fn valid_session_cannot_read_other_room_even_with_same_seat() {
        for bearer in [[1u8; 32], [2u8; 32]] {
            let other = ServerSkillWorld::from_authoritative_units_in_room(
                "other-match", 51, vec![unit("PRIVATE_OTHER_ROOM", Team::Blue)],
            ).unwrap();
            assert_eq!(gate().public_json(&bearer, &other, &[]),
                Err(SessionAuthError::Unauthorized));
            assert_eq!(gate().sse_frame(&bearer, &other, &[]),
                Err(SessionAuthError::Unauthorized));
        }
    }

    #[test]
    fn unbound_world_cannot_be_published_by_any_session() {
        let unbound = ServerSkillWorld::from_authoritative_units(
            51, vec![unit("unbound", Team::Blue)],
        ).unwrap();
        for bearer in [[1u8; 32], [2u8; 32]] {
            assert_eq!(gate().public_json(&bearer, &unbound, &[]),
                Err(SessionAuthError::Unauthorized));
        }
    }

    #[test]
    fn same_token_rotation_is_rejected_and_does_not_change_credentials() {
        let mut session = gate();
        assert_eq!(session.rotate(Team::Blue, [1u8; 32]),
            Err(SessionAuthError::InvalidTokenMaterial));
        assert_eq!(session.rotate(Team::Red, [2u8; 32]),
            Err(SessionAuthError::InvalidTokenMaterial));
        assert!(session.public_json(&[1u8; 32], &world(), &[]).is_ok());
        assert!(session.public_json(&[2u8; 32], &world(), &[]).is_ok());
    }

    #[test]
    fn empty_or_oversized_room_id_is_rejected_before_session_publication() {
        assert!(matches!(
            SessionGate::from_server_generated_tokens("", [1u8; 32], [2u8; 32]),
            Err(SessionAuthError::InvalidRoomId)
        ));
        assert!(matches!(
            SessionGate::from_server_generated_tokens(&"r".repeat(129), [1u8; 32], [2u8; 32]),
            Err(SessionAuthError::InvalidRoomId)
        ));
        assert_eq!(
            ServerSkillWorld::from_authoritative_units_in_room(
                "", 1, vec![unit("unit", Team::Blue)],
            ).unwrap_err(),
            crate::skill_authority::WorldSnapshotError::InvalidRoomId
        );
    }

    #[test]
    fn revocation_and_rotation_stay_scoped_to_bound_room() {
        let mut session = gate();
        session.revoke(Team::Blue);
        session.rotate(Team::Blue, [3u8; 32]).unwrap();
        let other = ServerSkillWorld::from_authoritative_units_in_room(
            "other-match", 50, vec![unit("another-blue", Team::Blue)],
        ).unwrap();
        assert!(session.sse_frame(&[3u8; 32], &world(), &[]).is_ok());
        assert_eq!(session.sse_frame(&[3u8; 32], &other, &[]),
            Err(SessionAuthError::Unauthorized));
        assert_eq!(session.sse_frame(&[1u8; 32], &world(), &[]),
            Err(SessionAuthError::Unauthorized));
    }
}
